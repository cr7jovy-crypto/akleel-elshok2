export function getChapterContent(book: BibleBook, chapter: number): ChapterContent {
  const key = `${book.name} ${chapter}`;
  if (FULL_CHAPTERS[key]) {
    return FULL_CHAPTERS[key];
  }

  if (book.id === 'acts' && ACTS_SUMMARIES[chapter]) {
    const info = ACTS_SUMMARIES[chapter];
    return {
      title: `سفر أعمال الرسل — الإصحاح ${chapter} (${info.title})`,
      isFullText: false,
      verses: [
        `ملخص الإصحاح ${chapter}: ${info.summary}`,
        `الآية المفتاحية للسفر: ${book.keyVerse} (${book.keyVerseRef})`,
      ],
      studyNote: `يمكنك قراءة النص الكامل المتاح حالياً في الإصحاحات ١، ٢، و٩ من سفر أعمال الرسل، ومتابعة الخط الزمني لبقية الإصحاحات الثمانية والعشرين دون اتصال بالإنترنت.`,
    };
  }

  return {
    title: `سفر ${book.name} — الإصحاح ${chapter}`,
    isFullText: false,
    verses: [
      `محور السفر (${book.name}): ${book.theme}.`,
      `الآية المفتاحية: ${book.keyVerse} — ${book.keyVerseRef}.`,
      `الكاتب: ${book.author} · عدد إصحاحات السفر: ${book.chapters} إصحاحاً.`,
    ],
    studyNote: `اختر الإصحاحات الكاملة المحملة أوفلاين (مثل متى ١ و٥ و٦، مرقس ١ و٤، لوقا ٢ و١٥، يوحنا ١ و٣ و١٤ و١٩ و٢٠، أعمال ١ و٢ و٩، رومية ٨، كورنثوس الأولى ١٣، فيلبي ٤، عبرانيين ١١، يعقوب ١، ورؤيا ٢١) لقراءة النص الكتابي الكامل.`,
  };
}

export function getFullTextChaptersForBook(bookName: string): number[] {
  return Object.keys(FULL_CHAPTERS)
    .filter((k) => k.startsWith(`${bookName} `))
    .map((k) => Number(k.split(' ').pop()))
    .filter((n) => !Number.isNaN(n));
}
